def test_ty_check_is_clean() -> None:
    """Run the project type checker exactly as the quality gate does."""
    result = subprocess.run(
        ["uv", "run", "--extra", "dev", "ty", "check", "src", "Agents/benchmark", "Main"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        timeout=600,
        check=False,
    )
    assert result.returncode == 0, (result.stdout + result.stderr)[-3000:]
