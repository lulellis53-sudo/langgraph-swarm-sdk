AGENT_MANIFESTS = sorted(AGENTS_DIR.rglob("agent.yaml"))
AGENT_IDS = [_rel(p.parent) for p in AGENT_MANIFESTS]


def test_agents_are_discovered() -> None:
    assert AGENT_MANIFESTS, "no agent.yaml found under Agents/"


def test_coordination_registry_is_valid() -> None:
    assert AgentValidator.validate_coordination(AGENTS_DIR) == []


def test_every_top_level_agent_dir_is_registered() -> None:
    """A persona folder with an ``agent.yaml`` but no coordination entry is dead config."""
    coordination = yaml.safe_load((AGENTS_DIR / "coordination.yaml").read_text(encoding="utf-8"))
    registered = {entry["name"] for entry in coordination["agents"]}
    on_disk = {p.parent.name for p in AGENT_MANIFESTS if p.parent.parent == AGENTS_DIR}
    assert on_disk <= registered, f"unregistered agents: {sorted(on_disk - registered)}"


@pytest.mark.parametrize("manifest_path", AGENT_MANIFESTS, ids=AGENT_IDS)
class TestAgentConfigured:
    """Each agent has a validated manifest, a role contract and no embedded secret."""

    @staticmethod
    def test_manifest_loads_and_matches_directory(manifest_path: Path) -> None:
        manifest = AgentManifestLoader.load_one(manifest_path)
        # Sub-personas are named ``Parent/Child`` (e.g. ``ModelDelegate/Router``).
        assert manifest.name == manifest_path.parent.relative_to(AGENTS_DIR).as_posix()
        assert manifest.role.strip()

    @staticmethod
    def test_model_and_key_source_are_set(manifest_path: Path) -> None:
        manifest = AgentManifestLoader.load_one(manifest_path)
        assert manifest.model, "model must be pre-selected"
        if manifest.model == "inherit":
            return  # Credential comes from the parent run; no key of its own.
        assert manifest.api_key_env, "api_key_env must name the credential source"
        assert re.fullmatch(r"[A-Z][A-Z0-9_]*", manifest.api_key_env), (
            "api_key_env holds an env-var NAME, never a value"
        )

    @staticmethod
    def test_declares_tasks_with_unique_ids(manifest_path: Path) -> None:
        manifest = AgentManifestLoader.load_one(manifest_path)
        ids = [task.id for task in manifest.tasks]
        assert ids, "agent declares no tasks"
        assert len(ids) == len(set(ids)), "duplicate task ids"
        assert all(task.description.strip() for task in manifest.tasks)

    @staticmethod
    def test_role_contract_present(manifest_path: Path) -> None:
        contract = manifest_path.parent / "AGENTS.md"
        assert contract.is_file(), f"missing {_rel(contract)}"
        assert contract.read_text(encoding="utf-8").strip()

    @staticmethod
    def test_manifest_holds_no_secret_value(manifest_path: Path) -> None:
        text = manifest_path.read_text(encoding="utf-8")
        assert SECRET_SHAPE.search(text) is None


