@pytest.mark.parametrize("path", SOURCE_FILES, ids=SOURCE_IDS)
class TestSourceFile:
    """Static conventions every ``src/swarm_sdk`` module must satisfy."""

    @staticmethod
    def test_module_docstring(path: Path) -> None:
        if path.name == "__init__.py" and not path.read_text(encoding="utf-8").strip():
            pytest.skip("empty package marker")
        assert ast.get_docstring(_parse(path)), f"{_rel(path)}: missing module docstring"

    @staticmethod
    def test_future_annotations_first(path: Path) -> None:
        """Project rule: ``from __future__ import annotations`` right after the docstring."""
        body = _parse(path).body
        if not body:
            pytest.skip("empty module")
        if isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant):
            body = body[1:]
        first = body[0] if body else None
        assert (
            isinstance(first, ast.ImportFrom)
            and first.module == "__future__"
            and any(alias.name == "annotations" for alias in first.names)
        ), f"{_rel(path)}: first statement must be `from __future__ import annotations`"

    @staticmethod
    def test_public_api_has_docstrings(path: Path) -> None:
        tree = _parse(path)
        missing: list[str] = []
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef) and _is_public(node.name):
                if not ast.get_docstring(node):
                    missing.append(f"class {node.name}:{node.lineno}")
        for fn, _ in _walk_defs(tree.body):
            if _is_public(fn.name) and not ast.get_docstring(fn):
                missing.append(f"def {fn.name}:{fn.lineno}")
        assert not missing, f"{_rel(path)}: missing docstrings: {missing}"

    @staticmethod
    def test_public_api_is_fully_annotated(path: Path) -> None:
        missing: list[str] = []
        for fn, is_method in _walk_defs(_parse(path).body):
            if not _is_public(fn.name) and fn.name != "__init__":
                continue
            args = fn.args
            params = [*args.posonlyargs, *args.args, *args.kwonlyargs]
            if args.vararg:
                params.append(args.vararg)
            if args.kwarg:
                params.append(args.kwarg)
            if is_method and params and params[0].arg in {"self", "cls"}:
                params = params[1:]
            bare = [a.arg for a in params if a.annotation is None]
            if bare:
                missing.append(f"{fn.name}:{fn.lineno} params {bare}")
            if fn.returns is None and fn.name != "__init__":
                missing.append(f"{fn.name}:{fn.lineno} return")
        assert not missing, f"{_rel(path)}: unannotated: {missing}"

    @staticmethod
    def test_staticmethods_take_no_receiver(path: Path) -> None:
        """A ``@staticmethod`` that names ``self``/``cls`` is a latent misuse."""
        bad: list[str] = []
        for node in ast.walk(_parse(path)):
            if not isinstance(node, ast.ClassDef):
                continue
            for item in node.body:
                if not isinstance(item, ast.FunctionDef | ast.AsyncFunctionDef):
                    continue
                first = item.args.args[0].arg if item.args.args else None
                if "staticmethod" in _decorator_names(item) and first in {"self", "cls"}:
                    bad.append(f"{node.name}.{item.name}:{item.lineno}")
        assert not bad, f"{_rel(path)}: {bad}"

    @staticmethod
    def test_heavy_imports_are_lazy(path: Path) -> None:
        """PEP 810 intent: heavy stacks load on first use, never at module import.

        ``lazy import`` needs 3.15; on 3.14 the compliant forms are a function-local import or
        an import under ``if TYPE_CHECKING``. Only module-level statements are inspected.
        """
        if _rel(path) in EAGER_HEAVY_ALLOWED:
            pytest.skip("leaf module; laziness enforced at its entry point")
        eager: list[str] = []
        for node in _module_level_imports(_parse(path).body):
            roots = (
                [alias.name.split(".")[0] for alias in node.names]
                if isinstance(node, ast.Import)
                else [(node.module or "").split(".")[0]]
            )
            eager.extend(f"{r}:{node.lineno}" for r in roots if r in HEAVY_MODULES)
        assert not eager, f"{_rel(path)}: eager heavy imports: {eager}"


def _module_level_imports(body: list[ast.stmt]) -> Iterator[ast.Import | ast.ImportFrom]:
    """Yield imports executed at import time (skips ``if TYPE_CHECKING`` and ``def`` bodies)."""
    for node in body:
        if isinstance(node, ast.Import | ast.ImportFrom):
            yield node
        elif isinstance(node, ast.If):
            test = ast.unparse(node.test)
            if "TYPE_CHECKING" not in test:
                yield from _module_level_imports(node.body)
            yield from _module_level_imports(node.orelse)
        elif isinstance(node, ast.Try):
            for block in (node.body, node.orelse, node.finalbody):
                yield from _module_level_imports(block)
            for handler in node.handlers:
                yield from _module_level_imports(handler.body)


