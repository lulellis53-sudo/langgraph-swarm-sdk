"""Codebase standards: agent configuration, docstrings, type hints, lazy imports, free-threading.

Every check is static (AST or manifest parsing) except the ``ty`` run, so the suite stays fast
and never imports the heavy optional stacks it is policing.
"""

from __future__ import annotations

import ast
import re
import subprocess
from collections.abc import Iterator
from pathlib import Path

import pytest
import yaml

from swarm_sdk.agents.manifest import AgentManifestLoader
from swarm_sdk.agents.validate import AgentValidator

ROOT = Path(__file__).resolve().parents[3]
AGENTS_DIR = ROOT / "Agents"
SRC = ROOT / "src" / "swarm_sdk"

#: Generated code is exempt (regenerated by ``python -m swarm_sdk.pb``).
EXCLUDED_PARTS = frozenset({"pb", "__pycache__"})

#: Packages that must never load at ``import swarm_sdk`` time. Until PEP 810 (3.15) ships
#: ``lazy import``, the 3.14 equivalent is a function-local import or ``TYPE_CHECKING``.
HEAVY_MODULES = frozenset(
    {
        "polars",
        "fastembed",
        "llama_cpp",
        "langchain",
        "langchain_core",
        "langgraph",
        "langgraph_swarm",
        "tokenizers",
        "onnxruntime",
        "torch",
        "faiss",
        "qdrant_client",
        "mem0",
        "pyopencl",
    }
)

#: Value shapes that indicate a pasted credential rather than an env-var name.
SECRET_SHAPE = re.compile(r"(sk-[A-Za-z0-9]{16,}|AIza[0-9A-Za-z_-]{20,}|[A-Za-z0-9]{40,})")


#: Leaf modules whose whole purpose is the heavy dependency. They are only reached through a
#: lazy entry point; ``test_import_laziness.py`` proves ``import swarm_sdk`` never loads them.
EAGER_HEAVY_ALLOWED = frozenset(
    {
        "src/swarm_sdk/core/checkpoint.py",
        "src/swarm_sdk/orchestrator/graph.py",
        "src/swarm_sdk/orchestrator/low_swarm.py",
        "src/swarm_sdk/server/graphs.py",
        "src/swarm_sdk/serving/http.py",
    }
)


def _source_files() -> list[Path]:
    """Return every library ``.py`` file subject to the standards."""
    return sorted(
        p for p in SRC.rglob("*.py") if not EXCLUDED_PARTS & set(p.relative_to(SRC).parts)
    )


def _rel(path: Path) -> str:
    return str(path.relative_to(ROOT))


def _parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8"), filename=str(path))


def _is_public(name: str) -> bool:
    return not name.startswith("_")


def _walk_defs(
    body: list[ast.stmt], *, in_class: bool = False
) -> Iterator[tuple[ast.FunctionDef | ast.AsyncFunctionDef, bool]]:
    """Yield public-scope function definitions as ``(node, is_method)``.

    Nested functions inside function bodies are implementation detail and are skipped.
    """
    for node in body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
            yield node, in_class
        elif isinstance(node, ast.ClassDef):
            yield from _walk_defs(node.body, in_class=True)


def _decorator_names(node: ast.FunctionDef | ast.AsyncFunctionDef) -> set[str]:
    names: set[str] = set()
    for dec in node.decorator_list:
        target = dec.func if isinstance(dec, ast.Call) else dec
        if isinstance(target, ast.Name):
            names.add(target.id)
        elif isinstance(target, ast.Attribute):
            names.add(target.attr)
    return names


SOURCE_FILES = _source_files()
SOURCE_IDS = [_rel(p) for p in SOURCE_FILES]


